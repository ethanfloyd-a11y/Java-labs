public class SumofNumbers {

    /**
     * @param args the command line arguments
     */
    public static void main(String[] args) {
        int sum = 0;
        for(int x = 1; x <= 100; x++){
            sum += x;
        }
        System.out.print("the sum  of the number from 1-100 is "+ sum);
    }
    
}
